/* Uma animacao de um prop: os quadros first..first+count-1 do pacote. */
typedef struct{
  const char*name;
  int first,count;
  float fps;
  int looped;
}bs_prop_anim_t;

typedef struct{
  const char*stage;   /* palco a que pertence */
  const char*name;    /* nome do prop no JSON */
  const char*tex;     /* "stages/<stage>/<name>.cfz4" sob a raiz */
  float x,y;          /* position, do JSON */
  float sx,sy;        /* scale, do JSON */
  float scrollx,scrolly;
  int z;              /* zIndex */
  int dance;          /* danceEvery em batidas, 0 = nunca danca */
  int start;          /* animacao inicial do JSON, -1 = o jogo nao diz */
  int frames;         /* quadros no pacote CFZ4 */
  int sw,sh;          /* tamanho de UM quadro, ja na escala do palco */
  int src_w,src_h;    /* tamanho do quadro no espaco do ORIGINAL (1280x720) */
  int anim_first,anim_count;  /* faixa em bs_prop_anims[] */
}bs_prop_t;

