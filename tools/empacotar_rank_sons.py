#!/usr/bin/env python3
"""Os OITO jingles do rank da Freeplay, de OGG para o PCM de 48 kHz do port.

POR QUE ESTE ARQUIVO EXISTE

O port nao tem decodificador de OGG (o `audsrv` aceita PCM cru), e o pacote de
dados do repositorio nao trazia nenhum dos sons de `ranks/`. Eles existem no
repositorio oficial de arte, em `preload/sounds/ranks/<nome>.ogg`, e sao citados
pelo `FreeplayState.hx` (v0.8.6) em dois `switch`:

    L1190-1197  `rankDisplayNew`, +0,1 s do display:  rankinbad |
                rankinperfect | rankinnormal
    L1232-1246  `rankAnimSlam`, no slam:              loss | good | great |
                excellent | perfect

Os oito entram no pacote porque qualquer rank e' alcancavel nas 27 musicas: o
rank sai do percentual (`Scoring.calculateRank`), nao de um caminho fixo. Nao ha'
como saber na hora do build qual deles vai tocar.

O QUE E', E O QUE NAO E'

Nao e' decodificador embutido -- e' a mesma escolha das musicas de game over e
da tela de resultado (`tools/empacotar_audio.py`), que tambem viram PCM no
pendrive. O `.ogg` nao vai para o console.

E' `playOnce` a volume 1 no original, entao o PCM vai sem atenuacao: o 0,7 do
`previewVolume` vale para o preview e nao para estes.

Uso:
    tools/empacotar_rank_sons.py --assets /tmp/fassets [--out build/packs/freeplay]
"""
import argparse
import os
import sys

import empacotar_audio as ea   # `converte` (44,1 -> 48 kHz) e RATE

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Os oito, na ordem em que o cabecalho os publica. O nome e' o mesmo do
# `Paths.sound('ranks/<nome>')` do original.
SONS = [
    "rankinbad", "rankinnormal", "rankinperfect",
    "loss", "good", "great", "excellent", "perfect",
]

CABECALHO = """/* GENERATED by tools/empacotar_rank_sons.py -- do not edit by hand.
 *
 * Os OITO jingles do rank da Freeplay (`preload/sounds/ranks/<nome>.ogg` do
 * repositorio oficial de arte), em PCM 48 kHz estereo, e o tamanho de cada um
 * em AMOSTRAS (pares L,R). O tamanho vem do arquivo convertido, nao de uma
 * tabela escrita a mao: e' o que o `audio_ring` le para saber quando o
 * jingle acabou (e o que o teste do PC cobra).
 *
 * Quem escolhe qual toca em cada instante e' `fp_aud_jingle_novo` /
 * `fp_aud_jingle_slam` (src/engine/freeplay_audio.c), com as linhas da fonte.
 */
#ifndef FREEPLAY_AUDIO_DADOS_H
#define FREEPLAY_AUDIO_DADOS_H

#define FP_AUD_SOM_DIR   "freeplay/som/"
#define FP_AUD_SONS_N    {n}

typedef struct {{
    const char *nome;        /* == Paths.sound('ranks/<nome>')      */
    unsigned int amostras;   /* pares L,R a 48 kHz                 */
    unsigned int bytes;      /* amostras * 4 (PCM s16 estereo)     */
}} fp_aud_som_t;

static const fp_aud_som_t fp_aud_sons[FP_AUD_SONS_N] = {{
{linhas}}};

#endif /* FREEPLAY_AUDIO_DADOS_H */
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assets", required=True, help="clone do funkin.assets")
    ap.add_argument("--out", default=os.path.join(PROJECT, "build", "packs", "freeplay"))
    ap.add_argument("--header", default=os.path.join(PROJECT, "src", "engine",
                                                     "freeplay_audio_dados.h"))
    args = ap.parse_args()

    destino_dir = os.path.join(args.out, "som")
    os.makedirs(destino_dir, exist_ok=True)

    linhas = []
    faltando = []
    total = 0
    for nome in SONS:
        ogg = os.path.join(args.assets, "preload", "sounds", "ranks", nome + ".ogg")
        if not os.path.isfile(ogg):
            faltando.append(nome)
            continue
        pcm = os.path.join(destino_dir, nome + ".pcm")
        tam, seg = ea.converte(ogg, pcm)
        if tam % 4:
            print("  FALHA: %s deu %d B, que nao e' multiplo de 4" % (nome, tam))
            return 1
        amostras = tam // 4
        total += tam
        linhas.append('    {"%s", %du, %du},   /* %.3f s */\n'
                      % (nome, amostras, tam, seg))
        print("  %-14s %7.3f s  %8d B  %7d amostras" % (nome, seg, tam, amostras))

    if faltando:
        print("  FALTANDO no clone de arte: " + ", ".join(faltando))
        return 1

    with open(args.header, "w", encoding="utf-8") as f:
        f.write(CABECALHO.format(n=len(linhas), linhas="".join(linhas)))
    print("  %d arquivo(s), %d B, cabecalho em %s" % (len(linhas), total, args.header))
    return 0


if __name__ == "__main__":
    sys.exit(main())
